"""Modular Groups & Euler's Totient — CLRS 31.3 (1e–4e) (1, 2, 3, 4).

The group Z_n*, Euler's φ(n), subgroups generated by an element, and Euler's/Fermat's theorems.
"""

from __future__ import annotations

import math
from pathlib import Path
import sys
import unittest

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[3]))


def _order(a: int, n: int) -> int | None:
    if math.gcd(a, n) != 1:
        return None
    x = a % n
    t = 1
    while x != 1 % n:
        x = (x * a) % n
        t += 1
    return t


def units(n: int) -> list[int]:
    """Elements of the multiplicative group Z_n* = { a : 0 < a < n, gcd(a, n) = 1 }."""
    return [a for a in range(1, max(n, 2)) if math.gcd(a, n) == 1]


def totient(n: int) -> int:
    """Euler's phi function from the prime factorisation: phi(n) = n * prod_{p|n} (1 - 1/p)."""
    phi = n
    p = 2
    while p * p <= n:
        if n % p == 0:
            while n % p == 0:
                n //= p
            phi -= phi // p
        p += 1
    if n > 1:
        phi -= phi // n
    return phi


def subgroup(a: int, n: int) -> list[int]:
    """The subgroup <a> = {a^0, a^1, ...} of Z_n* generated by a."""
    s = [1 % n]
    x = a % n
    while x != 1 % n:
        s.append(x)
        x = (x * a) % n
    return s


def is_primitive_root(g: int, n: int) -> bool:
    return _order(g, n) == totient(n)


def demo() -> str:
    lines: list[str] = []
    lines.append(f"Z_15* = {units(15)}  (φ(15) = {totient(15)})")
    sg2 = subgroup(2, 15)
    lines.append(f"subgroup <2> of Z_15* = {sg2}  (order {len(sg2)}, divides φ(15) = 8: Lagrange)")
    lines.append(f"subgroup <7> of Z_15* = {subgroup(7, 15)}")
    lines.append(f"φ(n) for n = 1..12: {[totient(n) for n in range(1, 13)]}")
    lines.append(f"Euler's theorem check: 7^φ(15) mod 15 = {pow(7, totient(15), 15)}")
    roots = [g for g in range(1, 13) if is_primitive_root(g, 13)]
    lines.append(f"primitive roots mod 13: {roots} ({len(roots)} = φ(φ(13)))")
    return "\n".join(lines) + "\n"


class Tests(unittest.TestCase):
    def test_totient_counts_units(self) -> None:
        for n in range(2, 300):
            self.assertEqual(totient(n), len(units(n)), f"n={n}")
        self.assertEqual(totient(1), 1)

    def test_lagrange_and_euler(self) -> None:
        for n in range(2, 80):
            phi = totient(n)
            for a in units(n):
                self.assertEqual(phi % len(subgroup(a, n)), 0, "subgroup order must divide phi(n)")
                self.assertEqual(pow(a, phi, n), 1)

    def test_primitive_root_counts(self) -> None:
        for p in (3, 5, 7, 11, 13, 17, 19, 23):
            self.assertEqual(sum(1 for g in range(1, p) if is_primitive_root(g, p)), totient(p - 1))
        self.assertFalse(any(is_primitive_root(g, 15) for g in range(1, 15)))


if __name__ == "__main__":
    print(demo(), end="")
